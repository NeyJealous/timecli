    public static ArtifactData Get(ArtifactType type)
    {
        int index = (int)type;
        if (index < 0 || index >= (int)ArtifactType.Total)
            throw new ArgumentOutOfRangeException(nameof(type));
        return All[index];
    }

    public static double GetModValue(ArtifactType type, ulong level) =>
        ArtifactMath.GetLinearModValue(Get(type), level);

    public static double GetUpgradeCost(ArtifactType type, ulong level) =>
        ArtifactMath.GetNewUpgradeCost(Get(type), level);
